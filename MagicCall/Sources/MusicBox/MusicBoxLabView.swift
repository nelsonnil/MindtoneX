import SwiftUI

/// Test lab: search a song, then compare the original preview with its music box version.
struct MusicBoxLabView: View {
    @EnvironmentObject private var model: AppModel
    @Environment(\.dismiss) private var dismiss
    @Environment(\.scenePhase) private var scenePhase
    @StateObject private var lab = MusicBoxLabController()
    @State private var replicateToken = ""

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 22) {
                Text("Pick a song and compare three versions: the original preview, the instant local version, or an AI version generated by MusicGen on Replicate. Everything plays through the iPhone speaker.")
                    .font(.caption)
                    .foregroundStyle(OracleTheme.textSecondary)
                    .fixedSize(horizontal: false, vertical: true)

                section(number: 1, title: "Song") {
                    LibrarySongSearchBlock(
                        pickedTrackID: lab.track?.id,
                        onPick: { lab.select($0, model: model) }
                    )
                }

                section(number: 2, title: "Listen") {
                    VStack(alignment: .leading, spacing: 12) {
                        status
                        stylePicker
                        Text(lab.options.style.blurb)
                            .font(.caption)
                            .foregroundStyle(OracleTheme.textSecondary)
                            .fixedSize(horizontal: false, vertical: true)
                        if !lab.events.isEmpty {
                            MusicBoxNotesStrip(events: lab.events)
                        }
                        HStack(spacing: 10) {
                            playButton(
                                title: "Original",
                                icon: "waveform",
                                playing: lab.playback == .original,
                                enabled: lab.canPlayOriginal,
                                gold: false
                            ) { lab.toggleOriginal(model: model) }
                            playButton(
                                title: lab.options.style.title,
                                icon: lab.options.style.icon,
                                playing: lab.playback == .musicBox,
                                enabled: lab.canPlayMusicBox,
                                gold: true
                            ) { lab.toggleMusicBox(model: model) }
                        }
                        if let note = lab.note {
                            Label(note, systemImage: "exclamationmark.triangle.fill")
                                .font(.caption)
                                .foregroundStyle(OracleTheme.coral)
                                .fixedSize(horizontal: false, vertical: true)
                        }
                        aiBlock
                    }
                }

                section(number: 3, title: "Local tuning") {
                    VStack(alignment: .leading, spacing: 10) {
                        VStack(alignment: .leading, spacing: 4) {
                            Text("Speed \(Int((lab.options.speed * 100).rounded()))%")
                                .font(.subheadline)
                                .foregroundStyle(OracleTheme.textPrimary)
                            Slider(value: $lab.options.speed, in: 0.6...1.2, step: 0.05)
                                .tint(OracleTheme.gold)
                        }
                        if lab.options.style.allowsBass {
                            Toggle("Bass notes", isOn: $lab.options.bass)
                        }
                        Toggle("Snap short notes to key", isOn: $lab.options.snapToKey)
                        if lab.options.style.allowsWindDown {
                            Toggle("Wind-down ending", isOn: $lab.options.windDown)
                        }
                        if lab.options.style.allowsHumanize {
                            Toggle("Human / mechanical irregularity", isOn: $lab.options.humanize)
                        }
                    }
                    .font(.subheadline)
                    .tint(OracleTheme.gold)
                }

                Text("Works best with a clear sung or played melody. Rap, heavy electronic or very dense mixes may come out unrecognisable — try another song in that case.")
                    .font(.caption2)
                    .foregroundStyle(OracleTheme.textSecondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
            .padding(16)
        }
        .scrollDismissesKeyboard(.interactively)
        .background(OracleTheme.screenGradient.ignoresSafeArea())
        .navigationTitle("Melody lab")
        .navigationBarTitleDisplayMode(.inline)
        .toolbar {
            ToolbarItem(placement: .confirmationAction) {
                Button("Done") {
                    lab.cancelAI()
                    lab.stopPlayback()
                    dismiss()
                }
            }
        }
        .preferredColorScheme(.dark)
        .onDisappear {
            lab.cancelAI()
            lab.stopPlayback()
        }
        .onChange(of: scenePhase) { _, phase in
            if phase == .background { lab.stopPlayback() }
        }
    }

    private var aiBlock: some View {
        VStack(alignment: .leading, spacing: 10) {
            Divider().overlay(OracleTheme.cardBorder)
            HStack(spacing: 8) {
                Image(systemName: "cloud.fill")
                    .foregroundStyle(OracleTheme.indigo)
                VStack(alignment: .leading, spacing: 1) {
                    Text("AI version · MusicGen Melody")
                        .font(.subheadline.weight(.semibold))
                        .foregroundStyle(OracleTheme.textPrimary)
                    Text("Generated online with the sound selected above")
                        .font(.caption2)
                        .foregroundStyle(OracleTheme.textSecondary)
                }
            }

            if lab.replicateConfigured {
                HStack {
                    Label("Replicate token \(lab.replicateTokenHint ?? "saved")", systemImage: "checkmark.circle.fill")
                        .font(.caption)
                        .foregroundStyle(OracleTheme.textSecondary)
                    Spacer()
                    Button("Remove") { lab.removeReplicateToken() }
                        .font(.caption.weight(.semibold))
                        .foregroundStyle(OracleTheme.coral)
                }
            } else {
                SecureField("Replicate API token", text: $replicateToken)
                    .textInputAutocapitalization(.never)
                    .autocorrectionDisabled()
                    .padding(12)
                    .background(Color.white.opacity(0.06))
                    .clipShape(RoundedRectangle(cornerRadius: 12, style: .continuous))
                HStack(spacing: 10) {
                    Button {
                        lab.saveReplicateToken(replicateToken)
                        if lab.replicateConfigured { replicateToken = "" }
                    } label: {
                        Text("Save token")
                            .font(.subheadline.weight(.semibold))
                            .frame(maxWidth: .infinity)
                            .padding(.vertical, 11)
                            .foregroundStyle(OracleTheme.ink)
                            .background(OracleTheme.goldGradient, in: RoundedRectangle(cornerRadius: 12, style: .continuous))
                    }
                    .buttonStyle(.plain)
                    .disabled(replicateToken.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty)
                    Link("Get a token", destination: ReplicateMusicBoxSettings.tokensURL)
                        .font(.subheadline.weight(.semibold))
                        .foregroundStyle(OracleTheme.gold)
                }
                Text("Create a free Replicate account, add billing or credit, and paste its API token here. It is stored only in this iPhone's Keychain.")
                    .font(.caption2)
                    .foregroundStyle(OracleTheme.textSecondary)
                    .fixedSize(horizontal: false, vertical: true)
            }

            aiStatus

            if lab.aiPhase.isGenerating {
                Button {
                    lab.cancelAI()
                } label: {
                    Label("Cancel generation", systemImage: "xmark.circle.fill")
                        .font(.subheadline.weight(.semibold))
                        .frame(maxWidth: .infinity)
                        .padding(.vertical, 12)
                        .foregroundStyle(OracleTheme.coral)
                        .background(Color.white.opacity(0.08), in: RoundedRectangle(cornerRadius: 12, style: .continuous))
                }
                .buttonStyle(.plain)
            } else {
                HStack(spacing: 10) {
                    Button {
                        lab.generateAI(model: model)
                    } label: {
                        Label(lab.canPlayAI ? "Generate again" : "Generate AI", systemImage: "wand.and.stars")
                            .font(.subheadline.weight(.semibold))
                            .frame(maxWidth: .infinity)
                            .padding(.vertical, 12)
                            .foregroundStyle(lab.canGenerateAI ? OracleTheme.textPrimary : OracleTheme.textSecondary)
                            .background(Color.white.opacity(lab.canGenerateAI ? 0.12 : 0.05), in: RoundedRectangle(cornerRadius: 12, style: .continuous))
                    }
                    .buttonStyle(.plain)
                    .disabled(!lab.canGenerateAI)

                    playButton(
                        title: "AI version",
                        icon: "waveform.and.magnifyingglass",
                        playing: lab.playback == .ai,
                        enabled: lab.canPlayAI,
                        gold: false
                    ) { lab.toggleAI(model: model) }
                }
            }

            Text("Each generation takes roughly 10–40 seconds and currently costs about $0.05 on Replicate. MusicGen may change some notes, so compare it with the original before using it in a show.")
                .font(.caption2)
                .foregroundStyle(OracleTheme.textSecondary)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    @ViewBuilder
    private var aiStatus: some View {
        switch lab.aiPhase {
        case .idle:
            Text(lab.track == nil ? "Pick a song first, then generate its AI version." : "Ready to generate the \(lab.options.style.title) version with AI.")
                .font(.caption)
                .foregroundStyle(OracleTheme.textSecondary)
        case .generating(let status):
            progressRow(status)
        case .ready:
            Label("AI version ready — tap “AI version” to listen.", systemImage: "checkmark.circle.fill")
                .font(.caption)
                .foregroundStyle(OracleTheme.gold)
        case .error(let message):
            Label(message, systemImage: "exclamationmark.triangle.fill")
                .font(.caption)
                .foregroundStyle(OracleTheme.coral)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    @ViewBuilder
    private var status: some View {
        switch lab.phase {
        case .idle:
            Text("Search above and tap a match.")
                .font(.caption)
                .foregroundStyle(OracleTheme.textSecondary)
        case .loading:
            progressRow("Downloading preview…")
        case .analyzing:
            progressRow("Listening for the melody…")
        case .ready:
            if let track = lab.track, let analysis = lab.analysis {
                VStack(alignment: .leading, spacing: 2) {
                    Text("\(track.title) — \(track.artist)")
                        .font(.subheadline.weight(.semibold))
                        .foregroundStyle(OracleTheme.textPrimary)
                        .lineLimit(1)
                    Text(summary(analysis))
                        .font(.caption)
                        .foregroundStyle(OracleTheme.textSecondary)
                }
            }
            if lab.rendering { progressRow("Re-tuning…") }
        case .error(let message):
            Label(message, systemImage: "exclamationmark.triangle.fill")
                .font(.caption)
                .foregroundStyle(OracleTheme.coral)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    private var stylePicker: some View {
        HStack(spacing: 8) {
            ForEach(MusicBoxStyle.allCases) { style in
                let selected = lab.options.style == style
                Button {
                    lab.options.style = style
                } label: {
                    VStack(spacing: 6) {
                        Image(systemName: style.icon)
                            .font(.body.weight(.semibold))
                        Text(style.title)
                            .font(.caption2.weight(.semibold))
                            .lineLimit(1)
                            .minimumScaleFactor(0.8)
                    }
                    .frame(maxWidth: .infinity)
                    .padding(.vertical, 10)
                    .foregroundStyle(selected ? OracleTheme.textPrimary : OracleTheme.textSecondary)
                    .background(
                        selected ? OracleTheme.gold.opacity(0.22) : Color.white.opacity(0.05),
                        in: RoundedRectangle(cornerRadius: 12, style: .continuous)
                    )
                    .overlay {
                        RoundedRectangle(cornerRadius: 12, style: .continuous)
                            .strokeBorder(selected ? OracleTheme.gold.opacity(0.8) : OracleTheme.cardBorder, lineWidth: selected ? 1.5 : 1)
                    }
                }
                .buttonStyle(.plain)
                .accessibilityAddTraits(selected ? .isSelected : [])
            }
        }
    }

    private func summary(_ analysis: MusicBoxAnalysis) -> String {
        var parts = ["\(lab.events.filter { $0.voice == .melody }.count) notes", analysis.keyName]
        if let bpm = analysis.bpm { parts.append("~\(Int(bpm.rounded())) BPM") }
        if let ms = lab.analysisMs { parts.append("\(ms) ms") }
        return parts.joined(separator: " · ")
    }

    private func progressRow(_ text: String) -> some View {
        HStack(spacing: 8) {
            ProgressView()
                .scaleEffect(0.85)
            Text(text)
                .font(.caption)
                .foregroundStyle(OracleTheme.textSecondary)
        }
    }

    private func playButton(
        title: String,
        icon: String,
        playing: Bool,
        enabled: Bool,
        gold: Bool,
        action: @escaping () -> Void
    ) -> some View {
        Button(action: action) {
            Label(playing ? "Stop" : title, systemImage: playing ? "stop.fill" : icon)
                .font(.subheadline.weight(.semibold))
                .frame(maxWidth: .infinity)
                .padding(.vertical, 14)
                .foregroundStyle(gold && enabled ? OracleTheme.ink : (enabled ? OracleTheme.textPrimary : OracleTheme.textSecondary))
                .background {
                    if gold && enabled {
                        RoundedRectangle(cornerRadius: 12, style: .continuous).fill(OracleTheme.goldGradient)
                    } else {
                        RoundedRectangle(cornerRadius: 12, style: .continuous).fill(Color.white.opacity(enabled ? 0.10 : 0.05))
                    }
                }
        }
        .buttonStyle(.plain)
        .disabled(!enabled)
    }

    private func section<Content: View>(number: Int, title: String, @ViewBuilder content: () -> Content) -> some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack(spacing: 8) {
                Text("\(number)")
                    .font(.caption.weight(.bold))
                    .frame(width: 22, height: 22)
                    .foregroundStyle(OracleTheme.ink)
                    .background(OracleTheme.gold, in: Circle())
                Text(title)
                    .font(.headline)
                    .foregroundStyle(OracleTheme.textPrimary)
            }
            content()
        }
    }
}

/// Piano-roll of the notes that will play (gold = melody, indigo = bass).
private struct MusicBoxNotesStrip: View {
    let events: [MusicBoxEvent]

    var body: some View {
        Canvas { context, size in
            guard let last = events.last else { return }
            let duration = max(1, last.time + 0.5)
            let lo = Double(MusicBoxArranger.displayRange.lowerBound)
            let hi = Double(MusicBoxArranger.displayRange.upperBound)
            for event in events where event.voice != .tick {
                let x = event.time / duration * size.width
                let y = (1 - (Double(event.midi) - lo) / (hi - lo)) * (size.height - 4)
                let width = max(3, event.duration / duration * size.width)
                let rect = CGRect(x: x, y: y, width: event.voice == .melody ? min(width, 12) : 3, height: 3)
                context.fill(
                    Path(roundedRect: rect, cornerRadius: 1),
                    with: .color(event.voice == .bass ? OracleTheme.indigo : OracleTheme.gold.opacity(Double(0.4 + 0.6 * event.velocity)))
                )
            }
        }
        .frame(height: 90)
        .padding(8)
        .background(Color.white.opacity(0.05), in: RoundedRectangle(cornerRadius: 12, style: .continuous))
        .accessibilityHidden(true)
    }
}
